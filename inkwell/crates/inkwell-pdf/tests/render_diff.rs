//! Plan 087: cross-renderer check that our ink is visible outside our app.
//!
//! Each fixture is saved with ink, then page 1 of the input and of the output
//! is rasterised by PDFium (annotations on) and by Ghostscript. The ink is the
//! set of pixels that changed between input and output; both renderers must
//! see ink, and in the same place (mask IoU), which catches "looks right in
//! my app only" regressions such as a broken /AP or a mis-flipped y-axis.
//!
//! The SPEC names MuPDF as well; Ghostscript is used because it is packaged
//! everywhere CI runs. Skipped loudly without gs/PDFium unless
//! `BEZIER_CONFORMANCE_STRICT=1`.

use std::path::PathBuf;
use std::process::Command;

use inkwell_core::doc::Document;
use inkwell_core::ink::{Brush, IdGen, StrokeBuilder, ToolKind};
use inkwell_core::pdf::{self, PdfFile};
use inkwell_pdf::{init_pdfium, normalise, Pdfium};
use pdfium_render::prelude::*;

const DPI: f64 = 72.0;
/// Per-pixel grey-level change that counts as "ink here".
const INK_DELTA: i32 = 48;
/// Minimum agreement between renderers' ink masks.
const MIN_IOU: f64 = 0.80;

struct Gray {
    w: usize,
    h: usize,
    px: Vec<u8>,
}

fn strict() -> bool {
    std::env::var("BEZIER_CONFORMANCE_STRICT").is_ok_and(|v| v == "1")
}

fn fixture(rel: &str) -> Vec<u8> {
    std::fs::read(PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../fixtures").join(rel)).expect("fixture")
}

/// Bold strokes across the page in a recognisable layout: a box, a diagonal
/// and a highlighter band. Positions are in page-local points from the top.
fn ink_doc(n_pages: usize) -> Document {
    let mut d = Document::for_pdf(n_pages);
    let mut ids = IdGen::seeded(0x5EED);
    let mut line = |d: &mut Document, kind: ToolKind, w: f64, pts: &[(f64, f64)]| {
        let mut b = StrokeBuilder::new(ids.next_id(), kind, [0.05, 0.05, 0.4], Brush { base_width: w, ..Default::default() }, false);
        for (i, &(x, y)) in pts.iter().enumerate() {
            b.push(x, y, 0.8, i as f64 * 8.0);
        }
        d.push_stroke(0, b.finish(0.0));
    };
    line(&mut d, ToolKind::Pen, 6.0, &[(80.0, 90.0), (380.0, 90.0), (380.0, 260.0), (80.0, 260.0), (80.0, 90.0)]);
    line(&mut d, ToolKind::Pen, 5.0, &[(90.0, 300.0), (200.0, 420.0), (320.0, 540.0)]);
    line(&mut d, ToolKind::Highlighter, 18.0, &[(100.0, 600.0), (420.0, 600.0)]);
    d
}

fn save(pdfium: &Pdfium, base: &[u8], d: &Document) -> Vec<u8> {
    let mut f = match PdfFile::open(base.to_vec()) {
        Ok(f) => f,
        Err(_) => PdfFile::open(normalise(pdfium, base).expect("normalise")).expect("open normalised"),
    };
    f.write_document(d, pdf::DEFAULT_GROUP).expect("write");
    f.finish()
}

fn render_pdfium(pdfium: &Pdfium, bytes: &[u8]) -> Gray {
    let doc = pdfium.load_pdf_from_byte_slice(bytes, None).expect("pdfium load");
    let page = doc.pages().get(0).expect("page 0");
    let w = (page.width().value as f64 * DPI / 72.0).round() as i32;
    let cfg = PdfRenderConfig::new()
        .set_target_width(w)
        .set_clear_color(PdfColor::WHITE)
        .render_annotations(true)
        .render_form_data(true);
    let bmp = page.render_with_config(&cfg).expect("render");
    let (bw, bh) = (bmp.width() as usize, bmp.height() as usize);
    let raw = bmp.as_raw_bytes();
    let stride = raw.len() / bh;
    let mut px = Vec::with_capacity(bw * bh);
    for y in 0..bh {
        for x in 0..bw {
            let o = y * stride + x * 4;
            // Channel order does not matter for a grey average.
            px.push(((raw[o] as u16 + raw[o + 1] as u16 + raw[o + 2] as u16) / 3) as u8);
        }
    }
    Gray { w: bw, h: bh, px }
}

fn render_gs(bytes: &[u8]) -> Gray {
    let dir = tempfile::tempdir().unwrap();
    let inp = dir.path().join("in.pdf");
    let out = dir.path().join("out.pgm");
    std::fs::write(&inp, bytes).unwrap();
    let st = Command::new("gs")
        .args(["-q", "-dNOPAUSE", "-dBATCH", "-dSAFER", "-sDEVICE=pgmraw", "-dFirstPage=1", "-dLastPage=1"])
        .args(["-dTextAlphaBits=4", "-dGraphicsAlphaBits=4"])
        .arg(format!("-r{DPI}"))
        .arg(format!("-sOutputFile={}", out.display()))
        .arg(&inp)
        .output()
        .expect("run gs");
    assert!(st.status.success(), "gs failed: {}", String::from_utf8_lossy(&st.stderr));
    parse_pgm(&std::fs::read(&out).unwrap())
}

fn parse_pgm(b: &[u8]) -> Gray {
    // P5 <ws> width <ws> height <ws> maxval <single ws> data; gs adds a
    // "# Image generated by…" comment line after the magic.
    let mut fields = Vec::new();
    let mut i = 0;
    while fields.len() < 4 {
        while b[i].is_ascii_whitespace() {
            i += 1;
        }
        if b[i] == b'#' {
            while b[i] != b'\n' {
                i += 1;
            }
            continue;
        }
        let s = i;
        while !b[i].is_ascii_whitespace() {
            i += 1;
        }
        fields.push(String::from_utf8_lossy(&b[s..i]).into_owned());
    }
    assert_eq!(fields[0], "P5");
    let (w, h): (usize, usize) = (fields[1].parse().unwrap(), fields[2].parse().unwrap());
    Gray { w, h, px: b[i + 1..i + 1 + w * h].to_vec() }
}

/// Pixels that changed by more than `INK_DELTA` between input and output.
fn ink_mask(before: &Gray, after: &Gray, w: usize, h: usize) -> Vec<bool> {
    let mut m = vec![false; w * h];
    for y in 0..h {
        for x in 0..w {
            let a = before.px[y * before.w + x] as i32;
            let b = after.px[y * after.w + x] as i32;
            m[y * w + x] = (a - b).abs() > INK_DELTA;
        }
    }
    m
}

/// IoU after dilating each mask by one pixel, to forgive anti-aliasing.
fn iou(a: &[bool], b: &[bool], w: usize, h: usize) -> f64 {
    let dilate = |m: &[bool]| {
        let mut d = m.to_vec();
        for y in 0..h {
            for x in 0..w {
                if m[y * w + x] {
                    for (dx, dy) in [(-1i64, 0i64), (1, 0), (0, -1), (0, 1)] {
                        let (nx, ny) = (x as i64 + dx, y as i64 + dy);
                        if nx >= 0 && ny >= 0 && (nx as usize) < w && (ny as usize) < h {
                            d[ny as usize * w + nx as usize] = true;
                        }
                    }
                }
            }
        }
        d
    };
    let (da, db) = (dilate(a), dilate(b));
    // Each mask is matched against the other's dilation, symmetric.
    let hit_a = a.iter().zip(&db).filter(|(x, y)| **x && **y).count();
    let hit_b = b.iter().zip(&da).filter(|(x, y)| **x && **y).count();
    let (na, nb) = (a.iter().filter(|x| **x).count(), b.iter().filter(|x| **x).count());
    if na == 0 || nb == 0 {
        return 0.0;
    }
    (hit_a as f64 / na as f64).min(hit_b as f64 / nb as f64)
}

#[test]
fn ink_renders_the_same_in_pdfium_and_ghostscript() {
    let has_gs = Command::new("gs").arg("--version").output().is_ok_and(|o| o.status.success());
    let pdfium = init_pdfium().ok();
    let (true, Some(pdfium)) = (has_gs, pdfium) else {
        assert!(!strict(), "render diff needs gs and PDFium (BEZIER_CONFORMANCE_STRICT=1)");
        eprintln!("WARNING render diff skipped: gs={has_gs}, PDFium missing or present");
        return;
    };

    for rel in ["conformance/classic.pdf", "conformance/xref_stream.pdf", "conformance/objstm_multi_page.pdf", "corpus/arxiv_adam.pdf"] {
        let base = fixture(rel);
        let n = pdfium.load_pdf_from_byte_slice(&base, None).unwrap().pages().len() as usize;
        let out = save(&pdfium, &base, &ink_doc(n));

        let (pb, pa) = (render_pdfium(&pdfium, &base), render_pdfium(&pdfium, &out));
        let (gb, ga) = (render_gs(&base), render_gs(&out));
        let w = pb.w.min(gb.w).min(pa.w).min(ga.w);
        let h = pb.h.min(gb.h).min(pa.h).min(ga.h);
        assert!(w > 100 && h > 100, "{rel}: implausible render size {w}x{h}");

        let pm = ink_mask(&pb, &pa, w, h);
        let gm = ink_mask(&gb, &ga, w, h);
        let (pn, gn) = (pm.iter().filter(|x| **x).count(), gm.iter().filter(|x| **x).count());
        // The three strokes cover roughly 4,000 px at 72 dpi.
        assert!(pn > 1500, "{rel}: PDFium shows almost no ink ({pn} px)");
        assert!(gn > 1500, "{rel}: Ghostscript shows almost no ink ({gn} px)");
        let score = iou(&pm, &gm, w, h);
        eprintln!("{rel}: ink px pdfium={pn} gs={gn} agreement={score:.3}");
        assert!(score >= MIN_IOU, "{rel}: renderers disagree on where the ink is (agreement {score:.3} < {MIN_IOU})");
    }
}
